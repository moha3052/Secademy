import fs from "node:fs/promises";
import ts from "typescript";
async function load(file) {
  const source = (await fs.readFile(file, "utf8")).replace(
    /import\s+["']server-only["'];?/g,
    "",
  );
  const code = ts.transpileModule(source, {
    compilerOptions: {
      module: ts.ModuleKind.ESNext,
      target: ts.ScriptTarget.ES2022,
    },
  }).outputText;
  return import(
    `data:text/javascript;base64,${Buffer.from(code).toString("base64")}`
  );
}
const { courses, lab } = await load("src/content/courses.ts");
const { questions } = await load("src/features/quizzes/questions.ts");
const { answers } = await load("src/features/quizzes/answers.ts");
const quote = (value) =>
  typeof value === "boolean"
    ? String(value)
    : typeof value === "number"
      ? String(value)
      : `'${String(value).replaceAll("'", "''")}'`;
const rows = [
  "-- Generated by npm run seed:generate. Edit original content, then regenerate.",
  "begin;",
];
function insert(table, data) {
  const keys = Object.keys(data);
  rows.push(
    `insert into ${table} (${keys.join(",")}) values (${Object.values(data).map(quote).join(",")}) on conflict (${keys[0]}) do update set ${keys
      .slice(1)
      .map((k) => `${k}=excluded.${k}`)
      .join(",")};`,
  );
}
for (const course of courses) {
  insert("public.courses", {
    id: course.id,
    slug: course.slug,
    title: course.title,
    description: course.description,
    published: true,
  });
  course.modules.forEach((module, index) => {
    const moduleId = `${course.id}-${index + 1}`;
    insert("public.modules", {
      id: moduleId,
      course_id: course.id,
      title: module.title,
      position: index + 1,
    });
    module.lessons.forEach((lesson, i) => {
      insert("public.lessons", {
        id: lesson.id,
        module_id: moduleId,
        slug: lesson.id,
        title: lesson.title,
        content_reference: lesson.file,
        position: i + 1,
        published: true,
      });
      insert("public.quizzes", {
        id: lesson.id,
        lesson_id: lesson.id,
        title: `Test: ${lesson.title}`,
      });
      questions[lesson.id].forEach((question, j) => {
        const questionId = `${lesson.id}-${j}`;
        insert("public.questions", {
          id: questionId,
          quiz_id: lesson.id,
          question_type: question.type,
          prompt: question.prompt,
          position: j,
        });
        question.options.forEach((label, k) =>
          insert("public.question_options", {
            id: `${questionId}-${k}`,
            question_id: questionId,
            label,
            position: k,
          }),
        );
        insert("private.answer_keys", {
          question_id: questionId,
          correct_position: answers[lesson.id].correct[j],
          explanation: answers[lesson.id].explanations[j],
        });
      });
    });
  });
}
insert("public.labs", {
  id: lab.id,
  title: lab.title,
  description: "Undersøg og begræns adgang til en lokal øvelsesfil.",
  published: true,
});
rows.push("commit;");
await fs.writeFile("supabase/seed.sql", rows.join("\n") + "\n");
console.log(
  "Generated repeatable seed for two courses, ten modules, nineteen lessons and quizzes, and one lab.",
);
